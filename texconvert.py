texpairs = [ ['\n', '\\\\'], ['&', '\\&'], ['—', '---'], ['–', '--'], \
    ['—', '\\textemdash{}'], ['—', '\\textemdash '], ['—', '\\textemdash'], \
    ['–', '\\textendash{}'], ['–', '\\textendash '], ['–', '\\textendash'], \
    ['á', "\\'a"], ['à', '\\`a'], ['â', '\\^a'], ['ã', '\\~a'], ['ä', '\\"a'], \
    ['é', "\\'e"], ['è', '\\`e'], ['ê', '\\^e'], ['ẽ', '\\~i'], ['ë', '\\"i'], \
    ['í', "\\'i"], ['ì', '\\`i'], ['î', '\\^i'], ['ĩ', '\\~e'], ['ï', '\\"e'], \
    ['ó', "\\'o"], ['ò', '\\`o'], ['ô', '\\^o'], ['õ', '\\~o'], ['ö', '\\"o'], \
    ['ú', "\\'u"], ['ù', '\\`u'], ['û', '\\^u'], ['ũ', '\\~u'], ['ü', '\\"u'], \
    ['Á', "\\'A"], ['À', '\\`A'], ['Â', '\\^A'], ['Ã', '\\~A'], ['Ä', '\\"A'], \
    ['É', "\\'E"], ['È', '\\`E'], ['Ê', '\\^E'], ['Ẽ', '\\~E'], ['Ë', '\\"E'], \
    ['Í', "\\'I"], ['Ì', '\\`I'], ['Î', '\\^I'], ['Ĩ', '\\~I'], ['Ï', '\\"I'], \
    ['Ó', "\\'O"], ['Ò', '\\`O'], ['Ô', '\\^O'], ['Õ', '\\~O'], ['Ö', '\\"O'], \
    ['Ú', "\\'U"], ['Ù', '\\`U'], ['Û', '\\^U'], ['Ũ', '\\~U'], ['Ü', '\\"U'], \
    ['ç', '\\c{c}'], ['Ç', '\\c{C}'], ['ç', '\\c c'], ['Ç', '\\c C'], \
    ['ñ', '\\~n'], ['Ñ', '\\~N'], ['ÿ', '\\"y'], ['Ÿ', '\\"Y'] ]

def texconvert(id0, text):  # id0 may be 0 or 1
    id1 = 1-id0             # id1 may be -1 or 0
    old = text
    for pair in texpairs:
        text = text.replace(pair[id0], pair[id1])
    return text

